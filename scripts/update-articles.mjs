#!/usr/bin/env node
// Refreshes data/articles.js from the public Secured Intel posts API.
//   node scripts/update-articles.mjs            -> fetches https://www.securedintel.com/api/posts
//   node scripts/update-articles.mjs posts.json -> reads a previously downloaded copy
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const API = 'https://www.securedintel.com/api/posts';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'data', 'articles.js');

const TAGS = [
  ['Forensics', /forensic|dfir|evidence|incident response/i],
  ['Vulnerability', /cve-|zero-day|0-day|vulnerab|rce|flaw|bypass|patch|exploit/i],
  ['AI', /\bai\b|llm|genai|claude|openai|chatgpt|deepfake|machine learning|\bml\b|agentic/i],
  ['Threat Actors', /apt|ransomware|malware|botnet|trojan|stealer|backdoor|spy|worm|muddywater|shinyhunters|lazarus/i],
  ['Supply Chain', /supply chain|npm|pypi|package|sdk|github|open source/i],
  ['Phishing & Fraud', /phish|fraud|scam|credential|mfa|social engineering|impersonat/i],
  ['OSINT & Dark Web', /osint|socmint|dark web|underground|intelligence/i],
  ['Cloud', /cloud|aws|azure|microsoft 365|saas|kubernetes/i],
  ['Privacy & Breaches', /breach|leak|privacy|stolen|exposed|hacked/i],
];

const plain = (md) => md
  .replace(/```[\s\S]*?```/g, ' ')
  .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
  .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
  .replace(/^\s*#{1,6}\s.*$/gm, ' ')
  .replace(/^\s*[|>*-].*$/gm, ' ')
  .replace(/[*_`~]/g, '')
  .replace(/\s+/g, ' ')
  .trim();

function excerpt(content, title) {
  let text = plain(content);
  if (text.toLowerCase().startsWith(title.toLowerCase())) text = text.slice(title.length).trim();
  if (text.length <= 190) return text;
  const cut = text.slice(0, 190);
  return cut.slice(0, cut.lastIndexOf(' ')) + '…';
}

const raw = process.argv[2]
  ? JSON.parse(await readFile(process.argv[2], 'utf8'))
  : await (await fetch(API)).json();

const articles = raw
  .filter((p) => p.published)
  .map((p) => {
    const title = p.title.trim();
    const tags = TAGS.filter(([, re]) => re.test(title)).map(([t]) => t).slice(0, 3);
    return {
      title,
      slug: p.slug,
      date: p.createdAt.slice(0, 10),
      image: p.imageUrl || '',
      excerpt: excerpt(p.content || '', title),
      minutes: Math.max(1, Math.round((p.content || '').split(/\s+/).length / 220)),
      tags: tags.length ? tags : ['News'],
    };
  })
  .sort((a, b) => b.date.localeCompare(a.date));

const banner = `// Generated by scripts/update-articles.mjs from ${API} — do not edit by hand.\n`;
await writeFile(OUT, `${banner}window.ARTICLES_UPDATED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};\nwindow.ARTICLES = ${JSON.stringify(articles)};\n`);
console.log(`Wrote ${articles.length} articles to ${path.relative(process.cwd(), OUT)}`);
